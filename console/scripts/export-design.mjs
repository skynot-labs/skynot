import { readFile, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve, dirname } from "node:path";

// JSON is the source of truth. CSS, portable exports and SVG assets are derived.
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(
  await readFile(resolve(root, "src/design/tokens.json"), "utf8"),
);
const logo = JSON.parse(
  await readFile(resolve(root, "src/design/logo.json"), "utf8"),
);
const prefix = (group, name) => `--sk-${group}-${name}`;
const declarations = Object.entries(tokens)
  .filter(([group]) => group !== "version" && group !== "semantic")
  .flatMap(([group, values]) =>
    Object.entries(values).map(
      ([name, value]) => `  ${prefix(group, name)}: ${value};`,
    ),
  );
for (const [name, reference] of Object.entries(tokens.semantic)) {
  const [group, key] = reference.split(".");
  if (!tokens[group]?.[key])
    throw new Error(`Unknown token reference: ${reference}`);
  declarations.push(`  --sk-${name}: var(${prefix(group, key)});`);
}
const aliases = {
  bg: "canvas",
  panel: "surface",
  scene: "scene",
  border: "border",
  text: "text",
  muted: "muted",
  mint: "mint",
  lavender: "lavender",
  peach: "peach",
  blue: "blue",
};
for (const [name, target] of Object.entries(aliases))
  declarations.push(`  --${name}: var(--sk-color-${target});`);
declarations.push(
  "  --sans: var(--sk-font-sans);",
  "  --mono: var(--sk-font-mono);",
);
const css = `/* Generated by npm run design:export. Edit console/src/design/tokens.json. */\n:root {\n  color-scheme: dark;\n${declarations.join("\n")}\n}\n`;
await mkdir(resolve(root, "public/brand"), { recursive: true });
await writeFile(resolve(root, "src/design/tokens.css"), css);
await writeFile(resolve(root, "public/brand/skynot.tokens.css"), css);
await writeFile(
  resolve(root, "public/brand/skynot.tokens.json"),
  JSON.stringify(tokens, null, 2) + "\n",
);

// Outlined glyphs: these logos do not depend on a font being installed.
const letters = `<path d="M22 13H10C1 13 1 25 10 25h5c9 0 9 12 0 12H3M33 3v34m19-24L34 26m6-4 14 15M64 13l10 22m13-22L73 45M99 37V13m0 10c0-14 24-14 24 0v14M155 25c0 16-25 16-25 0s25-16 25 0ZM170 4v26c0 6 4 7 10 7m-20-24h21"/>`;
const { mint, text, ink } = tokens.color;
function mark(color, trace = false) {
  return `<path ${trace ? 'class="trace" pathLength="1"' : ""} d="${logo.mark.path}" fill="none" stroke="${color}" stroke-width="${logo.mark.strokeWidth}" stroke-linecap="round" stroke-linejoin="round"/>`;
}
function wordmark(color, dot) {
  return `<g fill="none" stroke="${color}" stroke-width="6.5" stroke-linecap="round" stroke-linejoin="round">${letters}</g><circle cx="196" cy="34" r="4" fill="${dot}"/>`;
}
function svg(viewBox, title, content) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" role="img" aria-labelledby="title"><title id="title">${title}</title>${content}</svg>\n`;
}
const traceStyle = `<style>.trace{stroke-dasharray:1;stroke-dashoffset:1;animation:draw 1400ms ease both}@keyframes draw{to{stroke-dashoffset:0}}@media(prefers-reduced-motion:reduce){.trace{animation:none;stroke-dashoffset:0}}</style>`;
const files = {
  "skynot-mark.svg": svg(
    logo.mark.viewBox,
    "Skynot continuous-line knot",
    mark(mint),
  ),
  "skynot-mark-ink.svg": svg(
    logo.mark.viewBox,
    "Skynot knot in ink",
    mark(ink),
  ),
  "skynot-mark-trace.svg": svg(
    logo.mark.viewBox,
    "How to draw the Skynot knot",
    traceStyle + mark(mint, true),
  ),
  "skynot-favicon.svg": svg(
    logo.mark.viewBox,
    "Skynot favicon",
    `<rect width="64" height="64" rx="15" fill="${mint}"/>${mark(ink)}`,
  ),
  "skynot-logo.svg": svg(
    "0 0 328 80",
    "Skynot logo for dark backgrounds",
    `<g transform="translate(0 8)">${mark(mint)}</g><g transform="translate(90 16) scale(1.12)">${wordmark(text, mint)}</g>`,
  ),
  "skynot-logo-ink.svg": svg(
    "0 0 328 80",
    "Skynot logo for light backgrounds",
    `<g transform="translate(0 8)">${mark(ink)}</g><g transform="translate(90 16) scale(1.12)">${wordmark(ink, mint)}</g>`,
  ),
  "skynot-logo-mono.svg": svg(
    "0 0 328 80",
    "Skynot monochrome logo",
    `<g transform="translate(0 8)">${mark(ink)}</g><g transform="translate(90 16) scale(1.12)">${wordmark(ink, ink)}</g>`,
  ),
  "skynot-wordmark.svg": svg(
    "0 0 208 52",
    "Skynot wordmark",
    `<g transform="translate(4 3)">${wordmark(text, mint)}</g>`,
  ),
};
for (const [name, content] of Object.entries(files))
  await writeFile(resolve(root, "public/brand", name), content);
console.log(
  `Design exports updated: CSS, JSON and ${Object.keys(files).length} SVG assets.`,
);
